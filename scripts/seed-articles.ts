async function seed() {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    throw new Error("Missing MONGODB_URI environment variable");
  }

  await mongoose.connect(uri);
  console.log("已連線到 MongoDB");

  await Article.deleteMany({});
  const created = await Article.insertMany(
    sampleArticles.map((article) => ({ ...article, slug: slugify(article.title) }))
  );
  console.log(`已建立 ${created.length} 篇文章：`);
  created.forEach((a) => console.log(`- ${a.title}`));

  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
